# After resampling + foreground crop we resize to a fixed cube for batching.
# Hardware: RTX A1000 8 GB dedicated VRAM
#   96³  @ batch=1 → ~5–6 GB peak  ✔  safe for all 3 models (ResNet18/DenseNet/Swin)
#   128³ @ batch=1 → ~10–12 GB peak ✖  OOM on DenseNet121 and SwinUNETR
# If you upgrade to a 16+ GB GPU, set all three to 128.
INPUT_DEPTH  = 96
